import { createContext, useContext, useEffect, useState } from "react";

// AuthContext manages the demo user session persisted in localStorage.
export const AuthContext = createContext(null);

const USER_STORAGE_KEY = "icm_user";

export function AuthProvider({ children }) {
  // Initialize user state directly from localStorage so page refreshes preserve login.
  const [user, setUser] = useState(() => {
    try {
      const savedUser = localStorage.getItem(USER_STORAGE_KEY);
      return savedUser ? JSON.parse(savedUser) : null;
    } catch {
      return null;
    }
  });

  // Sync user state changes to localStorage.
  useEffect(() => {
    if (user) {
      localStorage.setItem(USER_STORAGE_KEY, JSON.stringify(user));
    } else {
      localStorage.removeItem(USER_STORAGE_KEY);
    }
  }, [user]);

  function login(userData) {
    setUser(userData);
  }

  function logout() {
    setUser(null);
  }

  return (
    <AuthContext.Provider value={{ user, login, logout }}>
      {children}
    </AuthContext.Provider>
  );
}

export function useAuth() {
  return useContext(AuthContext);
}
